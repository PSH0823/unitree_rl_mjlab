# (Y_STOP - Y_START) / SPEED = 8 s) and the CV filter has had time to settle.
WINDOW_S = (4.0, 7.5)
SPEED_TOL = 0.2          # [m/s] on both twist magnitude and displacement rate
HEIGHT_RANGE = (0.7, 1.4)  # true visible height ~1.1 m (z band cuts < 0.10)
MIN_ID_FRACTION = 0.8



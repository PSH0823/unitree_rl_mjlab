"""3D-pipeline end-to-end gate (pipeline:=3d, HUMBLE ONLY): synthetic scene →
crop box → cloud_object_detector → autoware_multi_object_tracker, asserting
on /perception/tracked_objects:

  * the floor grid does not become an object (z-band works),
  * the pillar is tracked as a POLYGON with a plausible footprint and height,
  * its velocity estimate converges to the scene's commanded +y speed,
  * the track id stays stable through the crossing.

The scene is generated by scene_3d_source.py (no fixture bag, no MuJoCo);
its SPEED constant is the ground truth. Skips on Foxy, where the autoware
stack is not built (the 3D pipeline is Humble-only by decision, 2026-08-26).

Standalone:
  launch_test src/g1_perception/g1_perception_bringup/test/test_tracking_3d.launch_test.py
"""
